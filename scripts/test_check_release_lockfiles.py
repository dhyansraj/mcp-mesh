#!/usr/bin/env python3
"""Checks for scripts/check_release_lockfiles.py (#1407).

Every fixture uses versions (1.2.x / 9.9.x) that appear nowhere in the real
tree, so this file is invisible to both bump_version.py guards and can never
be dragged along by a bump.
"""

import contextlib
import importlib.util
import io
import pathlib
import subprocess
import tempfile

_spec = importlib.util.spec_from_file_location(
    "check_release_lockfiles",
    pathlib.Path(__file__).with_name("check_release_lockfiles.py"),
)
cl = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(cl)


CARGO = """# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "cc"
version = "{cc}"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aaaa"

[[package]]
name = "mcp-mesh-core"
version = "{mesh}"
dependencies = [
 "napi",
 "syn 2.0.119",
]

[[package]]
name = "napi"
version = "{napi}"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "bbbb"

[[package]]
name = "syn"
version = "2.0.119"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "cccc"
"""


def _cargo(mesh="1.2.3", cc="9.9.0", napi="9.9.1"):
    return CARGO.format(mesh=mesh, cc=cc, napi=napi)


def test_parse_cargo_lock_reads_every_package():
    pkgs = cl.parse_cargo_lock(_cargo())
    assert pkgs == {
        "cc": ["9.9.0"],
        "mcp-mesh-core": ["1.2.3"],
        "napi": ["9.9.1"],
        "syn": ["2.0.119"],
    }


def test_parse_cargo_lock_keeps_duplicate_names_apart():
    """`syn 2.0.119` and `syn 3.0.3` coexist in the real lock. Collapsing them
    to one value would hide a major-version fan-out — exactly the shape
    `cargo generate-lockfile` introduced on the 3.3.2 prep run."""
    text = _cargo() + """
[[package]]
name = "syn"
version = "3.0.3"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "dddd"
"""
    assert cl.parse_cargo_lock(text)["syn"] == ["2.0.119", "3.0.3"]


def test_parse_cargo_lock_ignores_indented_dependency_entries():
    """A package's `dependencies = [...]` array lists other crates by name and
    version. Those entries are indented; only column-0 keys are the block's
    own, and reading an indented one would invent packages."""
    pkgs = cl.parse_cargo_lock(_cargo())
    assert "napi\"," not in pkgs
    assert pkgs["mcp-mesh-core"] == ["1.2.3"]


def test_targeted_update_is_clean():
    """`cargo update --package mcp-mesh-core`: one version line moves."""
    moved, foreign = cl.cargo_lock_findings(_cargo(), _cargo(mesh="1.2.4"))
    assert moved
    assert foreign == []


def test_graph_re_resolution_is_caught():
    """`cargo generate-lockfile`: ours moves and so does everything else."""
    moved, foreign = cl.cargo_lock_findings(
        _cargo(),
        _cargo(mesh="1.2.4", cc="9.9.2", napi="9.9.3"),
    )
    assert moved
    assert foreign == ["cc: 9.9.0 -> 9.9.2", "napi: 9.9.1 -> 9.9.3"]


def test_added_and_removed_crates_are_caught():
    """A re-resolution can also pull a NEW transitive crate in or drop one.
    Comparing only the crates present in both files would miss both."""
    extra = """
[[package]]
name = "brand-new-crate"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "eeee"
"""
    moved, foreign = cl.cargo_lock_findings(_cargo(), _cargo(mesh="1.2.4") + extra)
    assert moved
    assert foreign == ["brand-new-crate: added at 0.1.0"]

    moved, foreign = cl.cargo_lock_findings(_cargo() + extra, _cargo(mesh="1.2.4"))
    assert moved
    assert foreign == ["brand-new-crate: removed (was 0.1.0)"]


def test_deliberate_dependency_bump_is_not_this_scripts_business():
    """Bumping Rust dependencies on purpose is fine — it just has to be its own
    reviewed change. Such a PR leaves mcp-mesh-core where it is, so the gate
    must not fire on it, or the check becomes something people route around."""
    moved, foreign = cl.cargo_lock_findings(_cargo(), _cargo(cc="9.9.2"))
    assert not moved
    assert foreign == ["cc: 9.9.0 -> 9.9.2"]


CHART_LOCK = """dependencies:
- name: mcp-mesh-postgres
  repository: file://../mcp-mesh-postgres
  version: {v}
- name: mcp-mesh-registry
  repository: file://../mcp-mesh-registry
  version: {v}
digest: sha256:{d}
generated: "2026-07-30T12:13:02.350465-04:00"
"""


def test_chart_lock_digest_and_timestamp_are_not_findings():
    moved, foreign = cl.chart_lock_findings(
        CHART_LOCK.format(v="1.2.3", d="aaa"),
        CHART_LOCK.format(v="1.2.4", d="bbb"),
    )
    assert moved
    assert foreign == []


def test_chart_lock_flags_a_foreign_chart_move():
    before = CHART_LOCK.format(v="1.2.3", d="aaa").replace(
        "digest:",
        "- name: postgresql\n  repository: https://charts.bitnami.com/bitnami\n"
        "  version: 15.1.0\ndigest:",
    )
    after = before.replace("1.2.3", "1.2.4").replace("15.1.0", "15.2.0")
    moved, foreign = cl.chart_lock_findings(before, after)
    assert moved
    assert foreign == ["postgresql: 15.1.0 -> 15.2.0"]


CHART_YAML = """apiVersion: v2
name: mcp-mesh-core
version: 1.2.3
dependencies:
  - name: mcp-mesh-postgres
    version: "{pv}"
    repository: "{pr}"
    condition: postgres.enabled
  - name: mcp-mesh-redis
    version: "1.2.3"
    repository: "file://../mcp-mesh-redis"
    condition: redis.enabled
maintainers:
  - name: Someone
"""


def test_chart_yaml_today_is_structurally_safe():
    """The finding #1407 asked to confirm: `helm dependency update` cannot pull
    an external chart version the way `cargo generate-lockfile` pulls crates,
    because every dependency is a file:// path at an exact version. It does
    refresh the remote repo cache, but has nothing remote to resolve."""
    text = CHART_YAML.format(pv="1.2.3", pr="file://../mcp-mesh-postgres")
    assert cl.parse_chart_dependencies(text) == [
        {
            "name": "mcp-mesh-postgres",
            "version": "1.2.3",
            "repository": "file://../mcp-mesh-postgres",
            "condition": "postgres.enabled",
        },
        {
            "name": "mcp-mesh-redis",
            "version": "1.2.3",
            "repository": "file://../mcp-mesh-redis",
            "condition": "redis.enabled",
        },
    ]
    assert cl.chart_dependency_violations(text) == []


def test_chart_yaml_remote_repository_is_a_violation():
    text = CHART_YAML.format(pv="1.2.3", pr="https://charts.bitnami.com/bitnami")
    violations = cl.chart_dependency_violations(text)
    assert len(violations) == 1
    assert "not a file:// path" in violations[0]


def test_chart_yaml_version_range_is_a_violation():
    for rng in ("^1.2.3", ">=1.2.0", "~1.2", "1.2.x", "*"):
        text = CHART_YAML.format(pv=rng, pr="file://../mcp-mesh-postgres")
        violations = cl.chart_dependency_violations(text)
        assert len(violations) == 1, (rng, violations)
        assert "is a range" in violations[0], rng


def test_chart_yaml_dependency_parse_stops_at_the_block_end():
    """`maintainers:` also holds `- name:` entries. Reading past the
    dependencies block would report a maintainer as an unpinned chart."""
    text = CHART_YAML.format(pv="1.2.3", pr="file://../mcp-mesh-postgres")
    assert all(d["name"] != "Someone" for d in cl.parse_chart_dependencies(text))


def test_empty_dependency_block_parses_as_empty():
    """The leaf charts declare `dependencies: []`; the inline empty list must
    not put the parser into the block and swallow the keys that follow."""
    text = "apiVersion: v2\ndependencies: []\nmaintainers:\n  - name: Someone\n"
    assert cl.parse_chart_dependencies(text) == []


def test_real_chart_yaml_passes():
    """Run the structural check against the chart actually in the tree, so the
    day a remote dependency is added this file goes red rather than the
    release."""
    chart = cl.PROJECT_ROOT / cl.CHART_YAML
    if not chart.exists():
        return
    deps = cl.parse_chart_dependencies(chart.read_text())
    assert deps, "mcp-mesh-core declares subcharts; the parser found none"
    assert cl.chart_dependency_violations(chart.read_text()) == []


def test_real_cargo_lock_parses():
    """Parsing the real lock is the only thing that proves the format
    assumptions still hold against whatever cargo writes today."""
    lock = cl.PROJECT_ROOT / cl.CARGO_LOCK
    if not lock.exists():
        return
    pkgs = cl.parse_cargo_lock(lock.read_text())
    assert cl.CARGO_MESH_PACKAGE in pkgs, sorted(pkgs)[:10]
    assert len(pkgs[cl.CARGO_MESH_PACKAGE]) == 1
    assert len(pkgs) > 100, len(pkgs)


# ---------------------------------------------------------------------------
# The base ref itself: a check that cannot fail is the defect this file exists
# to prevent, and reading a lockfile at an unresolvable ref used to be one.
# ---------------------------------------------------------------------------


@contextlib.contextmanager
def _temp_repo(with_cargo=True):
    """A throwaway git repo standing in for PROJECT_ROOT.

    Real git, because the thing under test is exactly how git reports a bad
    ref versus a missing path — a stubbed subprocess would let us assert our
    own assumption about that rather than git's behavior.
    """
    with tempfile.TemporaryDirectory() as d:
        root = pathlib.Path(d)
        run = lambda *a: subprocess.run(a, cwd=root, check=True, capture_output=True)
        run("git", "init", "-q")
        run("git", "config", "user.email", "t@example.com")
        run("git", "config", "user.name", "t")
        (root / cl.CHART_LOCK).parent.mkdir(parents=True, exist_ok=True)
        (root / cl.CHART_LOCK).write_text(CHART_LOCK.format(v="1.2.3", d="aaa"))
        (root / cl.CHART_YAML).write_text(
            CHART_YAML.format(pv="1.2.3", pr="file://../mcp-mesh-postgres")
        )
        if with_cargo:
            (root / cl.CARGO_LOCK).parent.mkdir(parents=True, exist_ok=True)
            (root / cl.CARGO_LOCK).write_text(_cargo())
        run("git", "add", "-A")
        run("git", "commit", "-q", "-m", "init")
        original = cl.PROJECT_ROOT
        cl.PROJECT_ROOT = root
        try:
            yield root
        finally:
            cl.PROJECT_ROOT = original


def _run_main(*argv):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        rc = cl.main(list(argv))
    return rc, buf.getvalue()


def test_unresolvable_base_ref_fails_instead_of_skipping():
    """An unfetched `origin/main`, a `HEAD^` on a root commit or a typo must
    exit non-zero.

    `git show <bad-ref>:<path>` and `git show <good-ref>:<missing-path>` both
    exit 128, so treating that as "cannot read; skipped" made the skip — which
    is a PASS — swallow a broken base ref. CI computes `origin/$BASE_REF` and
    needs that ref fetched, so this is reachable, and a lockfile gate that
    reports success having compared nothing is the failure mode the gate
    exists to prevent."""
    with _temp_repo() as root:
        # A bump is staged in the worktree: with a good ref this run would
        # compare and pass, so the non-zero exit can only come from the ref.
        (root / cl.CARGO_LOCK).write_text(_cargo(mesh="1.2.4"))
        rc, out = _run_main("--base", "origin/no-such-branch")
    assert rc == 1, out
    assert "origin/no-such-branch" in out
    assert "skipped" not in out


def test_absent_path_at_a_valid_ref_still_skips():
    """The skip path stays open for what it was meant for: a repo state where
    the lockfile genuinely is not there yet. That is not a broken check, so it
    must not turn the gate red."""
    with _temp_repo(with_cargo=False) as root:
        assert not (root / cl.CARGO_LOCK).exists()
        rc, out = _run_main("--base", "HEAD")
    assert rc == 0, out
    assert "Cargo.lock" in out and "skipped" in out


def test_ref_validation_bites():
    """The assertion above is only worth having if it goes red when the ref
    validation is removed, so remove it and require the failure."""
    original = cl._resolve_ref
    cl._resolve_ref = lambda ref: ref  # as if the check were never added
    try:
        try:
            test_unresolvable_base_ref_fails_instead_of_skipping()
        except AssertionError:
            return
        raise AssertionError(
            "the gate passed with an unresolvable base ref — the ref-validation "
            "test would not notice the check being deleted"
        )
    finally:
        cl._resolve_ref = original


